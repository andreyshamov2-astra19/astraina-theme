    public static function getTodayEvents(): array {
        $m = (int)date('n');
        $d = (int)date('j');
        return self::getEvents($m, $d);
    }

    public static function getMarqueeItem(): array {
        $events = self::getTodayEvents();
        $idx = (int)(time() / 15) % count($events);
        return $events[$idx];
    }
